"""Versioned economic meaning of the vendored cTrader cash-operation enum.

Account income is not automatically trading alpha. Unknown operations and sign
conflicts remain unresolved; provider notes never determine a classification.
"""
from decimal import Decimal

POLICY_VERSION='ctrader-cash-economic-classification/1.0.0'

EXTERNAL={
    'BALANCE_DEPOSIT','BALANCE_WITHDRAW','BALANCE_WITHDRAW_FOR_SUBACCOUNT',
    'BALANCE_DEPOSIT_TO_SUBACCOUNT','BALANCE_WITHDRAW_FROM_SUBACCOUNT',
    'BALANCE_DEPOSIT_FROM_SUBACCOUNT','BALANCE_DEPOSIT_TRANSFER','BALANCE_WITHDRAW_TRANSFER',
}
CREDIT={'BALANCE_DEPOSIT_NONWITHDRAWABLE_BONUS','BALANCE_WITHDRAW_NONWITHDRAWABLE_BONUS'}
SUPPORT={'BALANCE_DEPOSIT_CONVERTED_BONUS','BALANCE_DEPOSIT_NEGATIVE_BALANCE_PROTECTION'}
OTHER_BUSINESS={
    'BALANCE_DEPOSIT_IB_COMMISSIONS','BALANCE_WITHDRAW_IB_SHARED_PERCENTAGE',
    'BALANCE_DEPOSIT_IB_SHARED_PERCENTAGE_FROM_SUB_IB','BALANCE_DEPOSIT_IB_SHARED_PERCENTAGE_FROM_BROKER',
    'BALANCE_WITHDRAW_BONUS_COMPENSATION','BALANCE_WITHDRAW_IB_SHARED_PERCENTAGE_TO_BROKER',
    'BALANCE_DEPOSIT_MANAGEMENT_FEE','BALANCE_DEPOSIT_PERFORMANCE_FEE',
    'BALANCE_DEPOSIT_STRATEGY_COMMISSION_INNER','BALANCE_DEPOSIT_STRATEGY_COMMISSION_OUTER',
}
TRADING={
    'BALANCE_WITHDRAW_STRATEGY_COMMISSION_INNER','BALANCE_WITHDRAW_STRATEGY_COMMISSION_OUTER',
    'BALANCE_DEPOSIT_REBATE','BALANCE_WITHDRAW_REBATE','BALANCE_DEPOSIT_DIVIDENDS','BALANCE_WITHDRAW_DIVIDENDS',
    'BALANCE_WITHDRAW_GSL_CHARGE','BALANCE_WITHDRAW_ROLLOVER','BALANCE_DEPOSIT_SWAP','BALANCE_WITHDRAW_SWAP',
    'BALANCE_WITHDRAW_MANAGEMENT_FEE','BALANCE_WITHDRAW_COPY_FEE','BALANCE_WITHDRAW_INACTIVITY_FEE',
}

def classify(operation,delta):
    if not isinstance(delta,Decimal) or not delta.is_finite():raise ValueError('funding_finite_native_delta_required')
    group=next((name for names,name in ((EXTERNAL,'EXTERNAL_CAPITAL'),(CREDIT,'RESTRICTED_CREDIT'),
        (SUPPORT,'BROKER_SUPPORT_CAPITAL'),(OTHER_BUSINESS,'OTHER_BUSINESS_INCOME_OR_EXPENSE'),
        (TRADING,'ACCOUNT_INCOME_OR_EXPENSE')) if operation in names),'UNKNOWN')
    valid=group!='UNKNOWN' and not (operation.startswith('BALANCE_DEPOSIT') and delta<0 or operation.startswith('BALANCE_WITHDRAW') and delta>0)
    return {'policy_version':POLICY_VERSION,'category':group if valid else 'UNRESOLVED',
        'state':'CLASSIFIED' if valid else 'UNKNOWN_OPERATION' if group=='UNKNOWN' else 'NATIVE_SIGN_CONFLICT',
        'trade_alpha_claimed':False,'execution_authority':False}
